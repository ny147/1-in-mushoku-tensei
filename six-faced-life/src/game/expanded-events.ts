const studyXp = (l: Life) => {
  const p = getProgression(l);
  return p.magic[p.specialization].xp;
};
const known = (l: Life, school: MagicSchool) =>
  getProgression(l).magic[school].xp >= 35;
const living = (l: Life, id: string) =>
  l.family.some((p) => p.id === id) && !l.flags[`farewell-${id}`];

